"""Apple Device Tree (ADT) writer.

XNU's ``pexpert/device_tree.c`` parses a flattened Apple device tree, not an
FDT. The format is::

    node      = { u32 nprops, u32 nchildren, property*, node* }
    property  = { char name[32], u32 length, value padded to 4 bytes }

Every node has an implicit ``name`` property, written first. The high bit of
``length`` is reserved for flags and is kept at zero here.

The layout matches the ADT blobs generated by ``ios-sweet`` (``tools/adt.py``)
and ``xnu-on-pi`` (``tools/pi_adt.py``); this implementation is independent.
"""

from __future__ import annotations

import argparse
import struct
from dataclasses import dataclass, field
from pathlib import Path

MAX_NAME = 32
PAGE = 0x4000
SOC_BASE = 0x107C000000
UART_OFFSET = 0x001001000
UART_SIZE = 0x200
GIC_REGS = (
    0x003FF9000,
    0x1000,
    0x003FFA000,
    0x2000,
    0x003FFC000,
    0x2000,
    0x003FFE000,
    0x2000,
)
TIMEBASE_HZ = 54_000_000


def u32(value: int) -> bytes:
    """Encode a little-endian 32-bit property value."""
    return struct.pack("<I", value)


def u64(value: int) -> bytes:
    """Encode a little-endian 64-bit property value."""
    return struct.pack("<Q", value)


@dataclass
class Node:
    """One ADT node."""

    name: str
    props: list[tuple[str, bytes]] = field(default_factory=list)
    children: list[Node] = field(default_factory=list)

    def prop(self, name: str, value: bytes | str | int) -> Node:
        """Add a property and return this node for chaining."""
        encoded = _encode(value)
        if not name or len(name.encode()) >= MAX_NAME:
            raise ValueError(f"invalid property name: {name!r}")
        self.props.append((name, encoded))
        return self

    def child(self, name: str) -> Node:
        """Create a child node and return it."""
        node = Node(name)
        self.children.append(node)
        return node

    def build(self) -> bytes:
        """Serialize this node (and its subtree) to bytes."""
        return _serialize(self)


def _encode(value: bytes | str | int) -> bytes:
    if isinstance(value, bytes):
        return value
    if isinstance(value, str):
        return value.encode() + b"\0"
    if isinstance(value, int):
        return u64(value)
    raise TypeError(f"unsupported property value: {type(value)!r}")


def _serialize(node: Node) -> bytes:
    name = node.name.encode() + b"\0"
    if len(name) > MAX_NAME:
        raise ValueError(f"node name too long: {node.name!r}")

    props = [("name", name), *node.props]
    out = bytearray(struct.pack("<II", len(props), len(node.children)))
    for prop_name, value in props:
        raw_name = prop_name.encode()
        if len(raw_name) >= MAX_NAME:
            raise ValueError(f"property name too long: {prop_name!r}")
        out += raw_name.ljust(MAX_NAME, b"\0")
        out += struct.pack("<I", len(value) & 0x7FFFFFFF)
        out += value
        out += b"\0" * (-len(value) & 3)
    for child in node.children:
        out += _serialize(child)
    return bytes(out)


def pi5_adt(
    dram_base: int = 0x02000000,
    dram_size: int = 0x0FE000000,
    cmdline: str = "debug=0xc serial=1 cpus=1 keepsyms=1 -noprogress",
    timebase: int = TIMEBASE_HZ,
) -> bytes:
    """Build the reference ADT for the Raspberry Pi 5.

    ``dram_base``/``dram_size`` describe the kernel window, not the whole RAM.
    The bootloader replaces these with values parsed from the firmware FDT.
    """
    root = Node("device-tree")
    root.prop("compatible", "brcm,bcm2712")
    root.prop("model", "Raspberry Pi 5 Model B")

    chosen = root.child("chosen")
    chosen.prop("dram-base", u64(dram_base))
    chosen.prop("dram-size", u64(dram_size))
    chosen.prop("boot-args", cmdline)
    # XNU's early random wants a non-zero seed; the bootloader replaces this.
    chosen.prop("random-seed", bytes([0xA5]) * 256)
    chosen.child("memory-map")

    cpus = root.child("cpus")
    cpu0 = cpus.child("cpu0")
    cpu0.prop("state", "running")
    cpu0.prop("reg", u32(0))
    cpu0.prop("timebase-frequency", u32(timebase))
    cpu0.prop("bus-frequency", u32(100_000_000))
    cpu0.prop("memory-frequency", u32(400_000_000))
    cpu0.prop("peripheral-frequency", u32(100_000_000))
    cpu0.prop("fixed-frequency", u32(timebase))
    cpu0.prop("clock-frequency", u32(2_400_000_000))

    arm_io = root.child("arm-io")
    arm_io.prop("device_type", "soc")
    arm_io.prop("ranges", u64(0) + u64(SOC_BASE) + u64(0x04000000))

    uart = arm_io.child("uart0")
    uart.prop("compatible", "arm,pl011")
    uart.prop("AAPL,phandle", u32(1))
    uart.prop("reg", u64(UART_OFFSET) + u64(UART_SIZE))

    gic = arm_io.child("gic")
    gic.prop("device_type", "interrupt-controller")
    gic.prop("compatible", "arm,gic-400")
    gic.prop("interrupt-controller", "master")
    gic.prop("#interrupt-cells", u32(3))
    gic.prop("AAPL,phandle", u32(2))
    gic.prop("reg", b"".join(u64(value) for value in GIC_REGS))

    timer = arm_io.child("timer")
    timer.prop("device_type", "timer")
    timer.prop("compatible", "arm,armv8-timer")
    timer.prop("interrupt-parent", u32(2))
    timer.prop("interrupts", u32(1) + u32(11) + u32(0xF08))

    defaults = root.child("defaults")
    defaults.prop("serial-device", u32(1))

    return root.build()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build a Raspberry Pi 5 ADT blob")
    parser.add_argument("--out", type=Path, default=Path("build/pi5.adt"))
    parser.add_argument("--cmdline", default="debug=0xc serial=1 cpus=1 keepsyms=1 -noprogress")
    parser.add_argument("--dram-base", type=lambda x: int(x, 0), default=0x02000000)
    parser.add_argument("--dram-size", type=lambda x: int(x, 0), default=0x0FE000000)
    args = parser.parse_args(argv)

    blob = pi5_adt(
        dram_base=args.dram_base,
        dram_size=args.dram_size,
        cmdline=args.cmdline,
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(blob)
    print(f"wrote {args.out} ({len(blob)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
